//! Стоимость пути: упаковка трёх критериев в одно число.
//!
//! Порядок важности (как в ТЗ): 1) длина — самый короткий путь; 2) число колен — без
//! излишних колен; 3) «красота» — из равных путей берём тот, что ближе к середине
//! между карточками, и естественную сторону портов (выход справа, вход слева).

use super::model::Side;

/// Вес одной субединицы длины.
pub const LEN: u64 = 1 << 40;
/// Вес одного колена.
pub const BEND: u64 = 1 << 28;
/// Штраф за «неестественную» сторону порта (выход слева или вход справа).
pub const NONNATURAL: u64 = 4096;
/// Делитель отклонения от середины в третьем критерии.
pub const TIE_DIV: i32 = 8;

/// Найденный маршрут и его цена.
#[derive(Clone, Debug)]
pub struct Cand {
    pub cost: u64,
    pub points: Vec<(i32, i32)>,
    pub src: Side,
    pub dst: Side,
}

impl Cand {
    pub fn new(cost: u64, points: Vec<(i32, i32)>, src: Side, dst: Side) -> Self {
        Self {
            cost,
            points,
            src,
            dst,
        }
    }

    /// Длина в субединицах.
    pub fn len(&self) -> u64 {
        self.cost / LEN
    }
}
