//! Веса стоимости. Приоритет строгий: длина → колена → «прочее» (неестественность, красота).
//! Тройка упакована в одно 64-битное число: длина × 2^40 + колена × 2^28 + прочее.

/// Вес одной субклетки длины.
pub const LEN_W: u64 = 1 << 40;
/// Вес одного колена.
pub const BEND_W: u64 = 1 << 28;
/// Штраф за неестественную сторону (результат слева или вход справа).
pub const NONNATURAL: u64 = 4096;
/// Делитель для штрафа «красоты» (отклонение от середины между карточками).
pub const TIE_DIV: i32 = 8;

/// Длина (субклетки) из упакованной стоимости.
pub fn cost_len(c: u64) -> u64 {
    c >> 40
}

/// Число колен из упакованной стоимости.
pub fn cost_bends(c: u64) -> u64 {
    (c >> 28) & 0xFFF
}
